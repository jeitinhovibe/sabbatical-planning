/**
 * Rebuilds vendor/ktx2-loader.js — the KTX2Loader for the 3D globe, bundled
 * against the global THREE that index.html already loads.
 *
 * three@0.147.0 is the last release with a UMD build (examples/js was removed
 * in r148), but KTX2Loader only ever shipped as an ES module, so it cannot be
 * dropped in with a <script> tag. This bundles it (plus its WorkerPool,
 * ktx-parse and zstddec dependencies) into an IIFE and hangs it off
 * window.THREE, matching how the rest of the page uses three.
 *
 * The 'three' import is redirected to the page's global instead of bundling a
 * second copy: the texture KTX2Loader returns has to be an instance of the same
 * THREE the globe renders with.
 *
 *   node scripts/build-ktx2-loader.mjs
 *
 * Output is committed — the site build does not need esbuild. Re-run this only
 * when the pinned three version changes.
 */
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
// three does not export ./package.json; its CJS entry is <root>/build/three.cjs.
const threeRoot = path.dirname(path.dirname(require.resolve('three')));
const loaderPath = path.join(threeRoot, 'examples/jsm/loaders/KTX2Loader.js');
const outPath = path.resolve('vendor/ktx2-loader.js');

// The names KTX2Loader imports from 'three'. Read them from the source rather
// than hand-maintaining a list that goes stale with the next three bump.
const source = await readFile(loaderPath, 'utf8');
const match = source.match(/import\s*\{([\s\S]*?)\}\s*from\s*['"]three['"]/);
if (!match) throw new Error('KTX2Loader no longer imports from "three" — update this script');
const names = match[1]
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);
if (!names.length) throw new Error('No named imports found on three');

const globalThree = {
  name: 'global-three',
  setup(build) {
    build.onResolve({ filter: /^three$/ }, () => ({ path: 'three', namespace: 'global-three' }));
    build.onLoad({ filter: /.*/, namespace: 'global-three' }, () => ({
      contents: [
        'const T = window.THREE;',
        ...names.map((n) => `export const ${n} = T.${n};`),
      ].join('\n'),
      loader: 'js',
    }));
  },
};

const result = await build({
  entryPoints: [loaderPath],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: '__ktx2',
  minify: true,
  legalComments: 'none',
  plugins: [globalThree],
});

const pkg = JSON.parse(await readFile(path.join(threeRoot, 'package.json'), 'utf8'));
const banner = `/* KTX2Loader ${pkg.version} (three.js, MIT) bundled for the page's global THREE.
 * Generated by scripts/build-ktx2-loader.mjs — do not edit by hand. */
`;
const body = result.outputFiles[0].text;
const wrapped = `${banner}(function () {
${body}
window.THREE.KTX2Loader = __ktx2.KTX2Loader;
})();
`;

await mkdir(path.dirname(outPath), { recursive: true });
await writeFile(outPath, wrapped);
console.log(`✓ vendor/ktx2-loader.js (${(wrapped.length / 1024).toFixed(1)}KB, three ${pkg.version})`);
